def parse_args(argv):
    parser = argparse.ArgumentParser(
        description="Convert the PNG icon sources into the native .inc tables.")
    parser.add_argument("--icon", action="append", default=[], metavar="NAME=FILE",
                        help="single icon; repeatable, order is preserved")
    parser.add_argument("--strip", metavar="FILE",
                        help="horizontal strip cut on the alpha bounding box")
    parser.add_argument("--alpha-cut", type=int, default=0, metavar="N",
                        help="alpha below N counts as empty when the strip is "
                             "split (default 0: any ink splits)")
    parser.add_argument("--cells", metavar="LIST",
                        help="comma-separated indices of the strip glyphs to "
                             "use, in order: for a strip whose drawing order "
                             "is not the order of the table (see --list-runs)")
    parser.add_argument("--note", action="append", default=[], metavar="TEXT",
                        help="line added to the generated header (repeatable): "
                             "use it to record how the drawings were mapped")
    parser.add_argument("--list-runs", action="store_true",
                        help="print the glyph inventory of --strip with sizes, "
                             "then exit")
    parser.add_argument("--names", metavar="LIST",
                        help="comma-separated names for the glyphs of --strip")
    parser.add_argument("--names-file", metavar="FILE",
                        help="file with one name per line, for long strips")
    parser.add_argument("--prefix", default="kIcon",
                        help="name prefix used when --names lists numbers/suffixes")
    parser.add_argument("--style", choices=("tray", "battery"), default="tray",
                        help="output template (default: tray)")
    parser.add_argument("--cpp-out", default="native/src/TrayIconAssets.inc",
                        help="C++ include file to write")
    parser.add_argument("--cs-out",
                        help="optional managed copy (TrayIconAssets.cs); the "
                             "native one is the single source of truth")
    parser.add_argument("--namespace", default="w7t",
                        help="namespace of the C++ file (default: w7t)")
    parser.add_argument("--sub-namespace", default="trayassets",
                        help="inner namespace (default: trayassets / battassets)")
    parser.add_argument("--make-samples", metavar="DIR",
                        help="draw standby sample PNGs in DIR and exit")
    return parser.parse_args(argv)


def collect_glyphs(args):
    glyphs = []
    for spec in args.icon:
        if "=" not in spec:
            raise SystemExit("error: --icon expects NAME=FILE, got '%s'" % spec)
        name, path = spec.split("=", 1)
        glyphs.append((c_identifier(name), trim(load_rgba(path)), path))
    if args.strip and args.list_runs:
        image = load_rgba(args.strip)
        spans = strip_slices(image, args.alpha_cut)
        log("%s: %d glyphs (alpha cut %d)" % (args.strip, len(spans), args.alpha_cut))
        for index, span in enumerate(spans):
            glyph = trim(image, (span[0], 0, span[1], image.size[1]))
            log("    %2d  x=%3d..%-3d  %dx%d"
                % (index, span[0], span[1] - 1, glyph.size[0], glyph.size[1]))
        raise SystemExit(0)
    if args.strip:
        image = load_rgba(args.strip)
        spans = strip_slices(image, args.alpha_cut)
        if args.cells:
            wanted = []
            for token in args.cells.split(","):
                token = token.strip()
                if not token:
                    continue
                if not token.isdigit():
                    raise SystemExit("error: --cells expects indices, got '%s'" % token)
                index = int(token)
                if index >= len(spans):
                    raise SystemExit("error: --cells asks glyph %d, the strip "
                                     "has %d" % (index, len(spans)))
                wanted.append(spans[index])
            spans = wanted
        if args.names_file:
            with open(args.names_file, "r", encoding="utf-8") as handle:
                names = [line.strip() for line in handle if line.strip()]
        elif args.names:
            names = [n.strip() for n in args.names.split(",") if n.strip()]
        else:
            names = []
        if not names:
            raise SystemExit("error: --strip needs --names or --names-file")
        if len(names) != len(spans):
            raise SystemExit(
                "error: %d names but %d glyphs found in %s"
                % (len(names), len(spans), args.strip))
        for name, span in zip(names, spans):
            glyph = trim(image, (span[0], 0, span[1], image.size[1]))
            glyphs.append((c_identifier(name), glyph, args.strip))
    return glyphs


def render_cpp(args, glyphs):
    lines = []
    if args.note:
        # Documented mapping: it lives in the file it describes, next to the
        # table, so a future replacement of the source PNG does not have to
        # guess which drawing went where.
        lines.append("/*")
        for note in args.note:
            lines.append(" * " + note)
        lines.append(" */")
        lines.append("")
    for name, image, source in glyphs:
        width, height = image.size
        lines.append("/* %s (%dx%d) <- %s */" % (name, width, height, source))
        lines.append("static const char %s[] = R\"W7B(" % name)
        lines.append(png_base64(image))
        lines.append(")W7B\";")
        lines.append("")
    entries = "".join("    { %s, %d, %d },\n" % (name, image.size[0], image.size[1])
                      for name, image, _ in glyphs)

    if args.style == "battery":
        header = BATTERY_HEADER
        footer = BATTERY_FOOTER % {"entries": entries, "count": len(glyphs)}
        sub = args.sub_namespace if args.sub_namespace != "trayassets" else "battassets"
    else:
        header = TRAY_HEADER
        index_lines = "".join("    Idx%s = %d,\n" % (name[1:] if name.startswith("k") else name, i)
                              for i, (name, _, _) in enumerate(glyphs))
        footer = TRAY_FOOTER % {"entries": entries, "idx": index_lines,
                                "count": len(glyphs)}
        sub = args.sub_namespace

    body = "%s\n#pragma once\n\nnamespace %s {\nnamespace %s {\n\n%s\n\n%s\n%s" % (
        header, args.namespace, sub, STRUCT, "\n".join(lines), footer)
    return body


def render_cs(args, glyphs):
    out = ["// Win7Taskbar - generated companion of the native include "
           "(see \"compilation files/icons_to_base64.py\").",
           "// The native table stays the single source of truth: this copy only "
           "exists for code that runs without the DLL.",
           "",
           "internal static class TrayIconAssets",
           "{",
           "    internal readonly record struct Icon(byte[] Png, int Width, int Height);",
           ""]
    for name, image, _ in glyphs:
        out.append("    internal static readonly Icon %s = new Icon(_%s, %d, %d);"
                   % (name, name, image.size[0], image.size[1]))
    out.append("")
    for name, image, _ in glyphs:
        data = png_base64(image).replace("\n", "")
        out.append("    private const string _%s = \"%s\";" % (name, data))
    out.append("}")
    out.append("")
    return "\n".join(out)


def main(argv=None):
    args = parse_args(argv if argv is not None else sys.argv[1:])

    if args.make_samples:
        make_samples(args.make_samples)
        return 0

    glyphs = collect_glyphs(args)
    if not glyphs:
        raise SystemExit("error: nothing to do: pass --icon and/or --strip")

    if args.style == "battery" and not args.cells and len(glyphs) != len(BATTERY_NAMES):
        raise SystemExit("error: the battery strip has %d glyphs, expected %d "
                         "(use --cells to pick the drawings in table order)"
                         % (len(glyphs), len(BATTERY_NAMES)))

    output = render_cpp(args, glyphs)
    directory = os.path.dirname(args.cpp_out)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(args.cpp_out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(output)
    log("wrote %s (%d glyphs)" % (args.cpp_out, len(glyphs)))
    for name, image, _ in glyphs:
        log("    %-16s %dx%d" % (name, image.size[0], image.size[1]))

    if args.cs_out:
        cs_directory = os.path.dirname(args.cs_out)
        if cs_directory:
            os.makedirs(cs_directory, exist_ok=True)
        with open(args.cs_out, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(render_cs(args, glyphs))
        log("wrote %s" % args.cs_out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
