def make_samples(out_dir: str) -> None:
    """Draws the placeholder source PNGs used when the real artwork is missing.

    Windows 7 tray metrics: 16x16 glyphs at 100% scaling, drawn here at 32x32
    so that they stay crisp when the shell scales them. These files are a
    development standby, not the official artwork: drop the real PNGs in
    assets/icon-sources/ with the same names and re-run the script.
    """
    os.makedirs(out_dir, exist_ok=True)
    size = 32
    white = (255, 255, 255, 255)
    dark = (40, 40, 40, 255)
    green = (86, 176, 66, 255)
    yellow = (228, 187, 60, 255)
    red = (200, 60, 50, 255)

    def draw_bars(level, muted):
        image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(image)
        for i in range(4):
            filled = (not muted) and i < level
            x0 = 6 + i * 6
            top = 22 - i * 4
            d.rectangle([x0, top, x0 + 4, 24],
                        fill=white if filled else (150, 150, 150, 255))
        if muted:
            d.line([5, 6, 26, 26], fill=red, width=3)
            for i in range(4):
                x0 = 6 + i * 6
                d.rectangle([x0, 22 - i * 4, x0 + 4, 24],
                            fill=(150, 150, 150, 255))
        return image

    def draw_battery(percent, colour):
        image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(image)
        d.rectangle([6, 8, 27, 24], outline=white, width=2)
        d.rectangle([27, 13, 29, 19], fill=white)
        inner = int((27 - 9) * percent / 100)
        if inner > 0:
            d.rectangle([9, 11, 9 + inner, 21], fill=colour)
        return image

    def draw_network(level):
        image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(image)
        for i in range(5):
            x0 = 4 + i * 5
            top = 24 - i * 4
            filled = i < level
            d.rectangle([x0, top, x0 + 3, 26],
                        fill=white if filled else (110, 110, 110, 255))
        return image

    def draw_warning(badge, colour):
        image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(image)
        d.polygon([(16, 4), (29, 27), (3, 27)], fill=yellow, outline=dark)
        d.text((13, 10), badge, fill=dark)
        return image

    # volume-0 = muted, volume-1..3 = low/medium/high (Windows 7 order).
    draw_bars(0, True).save(os.path.join(out_dir, "volume-0.png"))
    for level in range(1, 4):
        draw_bars(level, False).save(os.path.join(out_dir, "volume-%d.png" % level))
    for level in range(6):
        draw_network(level).save(os.path.join(out_dir, "network-%d.png" % level))
    draw_warning("!", None).save(os.path.join(out_dir, "network-warning.png"))
    draw_warning("x", None).save(os.path.join(out_dir, "network-not-working.png"))

    # One strip with the 31 battery glyphs, Windows 7 order.
    glyphs = []
    for percent in range(10, 101, 10):
        glyphs.append(draw_battery(percent, green))
    for percent in range(10, 101, 10):
        glyphs.append(draw_battery(percent, yellow))
    for percent in range(10, 70, 10):
        glyphs.append(draw_battery(percent, red))
    empty = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(empty).rectangle([6, 8, 27, 24], outline=(150, 150, 150, 255), width=2)
    glyphs.append(empty)
    nobatt = draw_battery(0, red)
    ImageDraw.Draw(nobatt).line([6, 8, 27, 24], fill=red, width=3)
    glyphs.append(nobatt)
    glyphs.append(draw_warning("!", None))
    charge_error = draw_battery(30, red)
    ImageDraw.Draw(charge_error).line([6, 24, 27, 8], fill=red, width=3)
    glyphs.append(charge_error)
    plug = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(plug)
    d.rectangle([13, 4, 19, 12], fill=white)
    d.line([16, 12, 16, 22], fill=white, width=3)
    d.line([11, 26, 21, 26], fill=white, width=3)
    glyphs.append(plug)

    strip = Image.new("RGBA", (size * len(glyphs), size), (0, 0, 0, 0))
    for index, glyph in enumerate(glyphs):
        strip.paste(glyph, (index * size, 0), glyph)
    strip_path = os.path.join(out_dir, "battery-strip.png")
    strip.save(strip_path)
    log("wrote %d tray PNGs and the battery strip in %s (%s)"
        % (7 + 2, out_dir, strip_path))


