STRUCT = "struct IconB64 { const char* b64; int nativeW; int nativeH; };"

TRAY_HEADER = """\
// Win7Taskbar - tray icon assets, generated by
// "compilation files/icons_to_base64.py" from the PNG sources in
// assets/icon-sources/ (never committed: see .gitignore).
//
// DO NOT EDIT BY HAND: re-run the script after replacing a source PNG.
//
// These are the icons Win7Taskbar shows by itself when the matching system
// icon cannot be read from Explorer (see TrayFallbackIcons.cpp): they are a
// fallback, never a replacement for a bitmap that is readable.
"""

TRAY_FOOTER = """\
/* Table: index -> glyph. Idx* names are provided by the enum below so that
 * the C++ code never depends on a position. */
static const IconB64 kAll[] = {
%(entries)s};

enum Idx {
%(idx)s    IdxCount = %(count)d,
};

} // namespace trayassets
} // namespace w7t
"""

BATTERY_HEADER = """\
// Win7Taskbar - battery icons cut from the strip supplied in
// assets/icon-sources/ (never committed: see .gitignore).
// Cut measured on the alpha bounding box of every glyph: no icon is invented
// and no size is hard-coded by hand.
//
// DO NOT EDIT BY HAND: re-run
//   python3 "compilation files/icons_to_base64.py" --style battery ...
//
// Order: 0-9 green (10..100%%), 10-19 yellow (10..100%%), 20-25 red (10..60%%),
// 26 empty/grey, 27 battery with X (missing), 28 warning triangle,
// 29 circle with X (charge error), 30 plug (AC).
"""

BATTERY_FOOTER = """\
/* Table: index -> glyph. */
static const IconB64 kAll[] = {
%(entries)s};

/* Idx* prefix so that it does not clash with the base64 array names. The
 * names say what the drawing shows, because that is what the callers pick:
 * the strip has no colour variants (the fill is white), so "low" and "full"
 * differ by the height of the fill, not by a colour. */
enum Idx {
    IdxLevelBase = 0,    /* on battery: + level 1..10 -> base + lvl - 1 */
    IdxChargingBase = 10,/* on AC, battery + plug: same level arithmetic */
    IdxLowBase = 20,     /* low/critical levels 1..6 */
    IdxEmpty = 26,       /* battery outline, no fill (unknown/absent) */
    IdxNoBatt = 27,      /* on AC with no battery at all */
    IdxWarn = 28,        /* warning triangle */
    IdxChargeErr = 29,   /* AC plug + red X: charging refuses */
    IdxCount = %(count)d,
};

} // namespace battassets
} // namespace w7t
"""

# The 31 glyph names of the Windows 7 battery strip, in order.
BATTERY_NAMES = (
    ["kGreen%d" % i for i in range(1, 11)]
    + ["kYellow%d" % i for i in range(1, 11)]
    + ["kRed%d" % i for i in range(1, 7)]
    + ["kEmpty", "kNoBatt", "kWarn", "kChargeErr", "kPlug"]
)

# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------


def log(message: str) -> None:
    print(message, flush=True)


def load_rgba(path: str) -> Image.Image:
    if not os.path.isfile(path):
        raise SystemExit("error: %s not found" % path)
    return Image.open(path).convert("RGBA")


def alpha_bbox(image: Image.Image, box=None):
    """Bounding box of the non-transparent pixels, or None when empty."""
    if box is not None:
        image = image.crop(box)
    return image.split()[3].getbbox()


def trim(image: Image.Image, box=None) -> Image.Image:
    bbox = alpha_bbox(image, box)
    if bbox is None:
        raise SystemExit("error: a glyph is fully transparent, nothing to cut")
    if box is not None:
        left, top = box[0], box[1]
        bbox = (bbox[0] + left, bbox[1] + top, bbox[2] + left, bbox[3] + top)
    return image.crop(bbox)


def strip_slices(image: Image.Image, alpha_cut: int = 0):
    """Column ranges of the glyphs of a horizontal strip.

    Glyphs are separated by transparent columns; the cut itself is then
    refined on each glyph's own alpha bounding box, so a strip with uneven
    spacing or a non-transparent background line still works as long as the
    columns between the glyphs are empty.

    ``alpha_cut`` is the alpha value below which a pixel counts as empty. The
    default (0) treats any non-zero alpha as ink, which keeps glyphs whose
    anti-aliasing bleeds one column into the neighbour together. Raising it
    (e.g. 16) separates two drawings that touch only through faint pixels,
    without any coordinate being written by hand.
    """
    alpha = image.split()[3]
    width, height = image.size
    pixels = alpha.load()
    columns = []
    for x in range(width):
        empty = True
        for y in range(height):
            if pixels[x, y] > alpha_cut:
                empty = False
                break
        columns.append(not empty)

    spans = []
    start = None
    for x, filled in enumerate(columns):
        if filled and start is None:
            start = x
        elif not filled and start is not None:
            spans.append((start, x))
            start = None
    if start is not None:
        spans.append((start, width))
    return spans


def png_base64(image: Image.Image) -> str:
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    data = base64.b64encode(buffer.getvalue()).decode("ascii")
    return "\n".join(textwrap.wrap(data, 108))


def c_identifier(name: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name or ""):
        raise SystemExit("error: '%s' is not a valid C++ identifier" % name)
    return name


