#!/usr/bin/env python3
# Win7Taskbar - icon sources -> base64 include files
# Copyright (c) 2026 Win7Taskbar contributors - GPL v3 or later
#
# Turns the PNG sources kept in assets/icon-sources/ into the C++ include
# files that the native core embeds, so that the DLL keeps no external
# dependency on any image file.
#
# The PNG sources are NEVER committed (see .gitignore): only the generated
# .inc files are, and they are the single source of truth for the managed and
# native sides (pass --cs-out only when a managed copy is really needed).
#
# Why the strip mode cuts on the alpha bounding box: a sprite strip drawn by
# hand has no exact grid, and hand-measured offsets are the classic source of
# "one pixel of the neighbour" artefacts. Cropping each glyph to the bounding
# box of its own non-transparent pixels makes the result independent of any
# measurement, and records the real native size of every glyph in the table.
#
# Requirements:
#     pip install pillow
#
# Examples:
#     # the tray icons (volume, network, battery strip) in one file
#     python3 "compilation files/icons_to_base64.py" \
#         --icon kVolume0=assets/icon-sources/volume-0.png \
#         --icon kVolume1=assets/icon-sources/volume-1.png \
#         ... \
#         --strip assets/icon-sources/battery-strip.png \
#         --prefix kBattery --names kBattery0,kBattery1,... \
#         --cpp-out native/src/TrayIconAssets.inc
#
#     # the battery strip of the flyout (31 glyphs, Windows 7 order)
#     python3 "compilation files/icons_to_base64.py" --style battery \
#         --strip assets/icon-sources/Bitmap303.png \
#         --names kGreen1,...kPlug \
#         --cpp-out native/src/BatteryAssets.inc

from __future__ import annotations

import argparse
import base64
import io
import os
import re
import sys
import textwrap

try:
    from PIL import Image, ImageDraw
except ImportError:  # pragma: no cover - handled as a user-facing error
    print("error: Pillow is required (pip install pillow)", file=sys.stderr)
    raise SystemExit(2)

